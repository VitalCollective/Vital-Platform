export function translate(language: AppLanguage, english: string, parameters?: Parameters): string {
  const template = language === 'cy' ? cy[english] ?? english : english;
  if (!parameters) return template;
  return Object.entries(parameters).reduce(
    (value, [key, replacement]) => value.replaceAll(`{${key}}`, String(replacement)),
    template,
  );
}

export function hasWelshUiTranslation(english: string): boolean {
  return Object.hasOwn(cy, english);
}
